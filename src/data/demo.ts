const accountsById = new Map(demoAccounts.map((account) => [account.id, account]));
const contactsById = new Map(demoContacts.map((contact) => [contact.id, contact]));

function defaultStatus(chatId: string): MessageStatus {
  const chat = demoChats.find((item) => item.id === chatId);
  const account = chat ? accountsById.get(chat.accountId) : undefined;
  return account?.readReceipts ? 'read' : 'delivered';
}

interface MessageExtras {
  reply?: MessageReply;
  reactions?: MessageReaction[];
  attachment?: MessageAttachment;
  status?: MessageStatus;
  edited?: boolean;
}

function fromContact(
  chatId: string,
  id: string,
  contactId: string,
  createdAt: string,
  text: string,
  extras: MessageExtras = {},
): ChatMessage {
  const contact = contactsById.get(contactId);
  if (!contact) throw new Error(`Unknown contact: ${contactId}`);
  return {
    id,
    chatId,
    senderId: contactId,
    senderName: contact.name,
    outgoing: false,
    createdAt,
    text,
    ...extras,
  };
}

function fromMe(
  chatId: string,
  id: string,
  createdAt: string,
  text: string,
  extras: MessageExtras = {},
): ChatMessage {
  return {
    id,
    chatId,
    senderId: 'me',
    senderName: 'Вы',
    outgoing: true,
    createdAt,
    text,
    status: extras.status ?? defaultStatus(chatId),
    ...extras,
  };
}

function systemMessage(
  chatId: string,
  id: string,
  createdAt: string,
  text: string,
): ChatMessage {
  return {
    id,
    chatId,
    senderId: 'system',
    senderName: 'Система',
    outgoing: false,
    createdAt,
    text,
    system: true,
  };
}

